"""Report building: JSON (schema 1), single-file HTML, terminal summary.

The scrub step is a safety net, not the primary defence: scan.py never
puts a password into a record, and redact_uri() masks URI passwords at
parse time. scrub_secrets() still walks the finished report and removes
any occurrence of a password that was used during the scan, so a bug
upstream cannot turn into a leaked credential in a delivered report.
"""
import html
