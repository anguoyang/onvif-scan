from .parse import redact_uri

FOOTER = "Generated by onvif-scan · https://site-ai-gateway.com/open-source/onvif-scan/"


def scrub_secrets(obj, secrets):
    if not secrets:
        return obj
    if isinstance(obj, str):
        out = obj
        for s in secrets:
            if s:
                out = out.replace(s, "***")
        return out
    if isinstance(obj, dict):
        return {k: scrub_secrets(v, secrets) for k, v in obj.items()}
    if isinstance(obj, list):
        return [scrub_secrets(v, secrets) for v in obj]
    return obj


def build_report(tool_version, scan_meta, devices, duration_s):
    summary = {"discovered": len(devices), "full": 0, "partial": 0,
               "discovered_only": 0, "unreachable": 0, "with_findings": 0}
    for d in devices:
        summary[d["level"].lower()] = summary.get(d["level"].lower(), 0) + 1
        if d["findings"]:
            summary["with_findings"] += 1
    return {
        "schema": 1, "kind": "onvif_inventory", "tool_version": tool_version,
        "generated_at": datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds"),
        "scan": {**scan_meta, "duration_s": round(duration_s, 1)},
        "summary": summary, "devices": devices, "notes": [],
    }


def write_json(report, path):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(report, f, ensure_ascii=False, indent=1)
        f.write("\n")


_LEVEL_MARK = {"FULL": "●", "PARTIAL": "◐", "DISCOVERED_ONLY": "○", "UNREACHABLE": "✕"}


def terminal_lines(report):
    lines = []
    for d in report["devices"]:
        info = d.get("device_info") or {}
        who = " ".join(x for x in (info.get("Manufacturer"), info.get("Model")) if x) or "(unknown)"
        prof = ""
        if d["profiles"]:
            p0 = d["profiles"][0]
            prof = " · %s %sx%s" % (p0.get("codec") or "?", p0.get("width") or "?",
                                    p0.get("height") or "?")
        lines.append("%s %-15s %-34s %s ch=%d%s%s" % (
            _LEVEL_MARK.get(d["level"], "?"), d.get("ip") or "?", who[:34], d["level"],
            d["channel_count"], prof, " PTZ" if d["ptz"]["present"] else ""))
    s = report["summary"]
    lines.append("— discovered %d · full %d · partial %d · discovered-only %d · "
                 "unreachable %d · with findings %d" % (
                     s["discovered"], s["full"], s["partial"], s["discovered_only"],
                     s["unreachable"], s["with_findings"]))
    return lines


def _esc(x):
    return html.escape(str(x)) if x is not None else "—"


